def ensure_default_market_data(data_dir: Path) -> Path:
    """Create the default CSV once and never overwrite an existing file."""
    data_dir.mkdir(parents=True, exist_ok=True)
    path = data_dir / "market_data.csv"
    if path.exists():
        return path
    try:
        with path.open("x", encoding="utf-8", newline="") as handle:
            handle.write(DEFAULT_MARKET_DATA)
    except FileExistsError:
        # Another startup process seeded the same shared volume first.
        pass
    return path
